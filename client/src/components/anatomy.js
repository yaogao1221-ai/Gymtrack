// Chaque muscle est décrit par quelques points sur la moitié gauche de l'image ; la droite est dessinée en miroir.
// k = groupe musculaire de l'appli (null = muscle décoratif, non touchable) ; a = direction des fibres (degrés) ;
// c = pièce centrale (pas de miroir). Les tendons et os visibles sont dans TENDONS.

// Courbe fermée lisse passant par les points (Catmull-Rom → Bézier). Un point [x, y, 1] reste anguleux.
export function smooth(pts, closed = true) {
  const n = pts.length; const P = (i) => pts[(i + n) % n];
  let d = `M${P(0)[0]} ${P(0)[1]}`;
  const last = closed ? n : n - 1;
  for (let i = 0; i < last; i++) {
    const p0 = closed || i > 0 ? P(i - 1) : P(i), p1 = P(i), p2 = P(i + 1), p3 = closed || i + 2 < n ? P(i + 2) : P(i + 1);
    const t = 1 / 6; const s1 = p1[2] ? 0 : 1; const s2 = p2[2] ? 0 : 1;
    const c1 = [p1[0] + (p2[0] - p0[0]) * t * s1, p1[1] + (p2[1] - p0[1]) * t * s1];
    const c2 = [p2[0] - (p3[0] - p1[0]) * t * s2, p2[1] - (p3[1] - p1[1]) * t * s2];
    d += ` C${c1[0].toFixed(2)} ${c1[1].toFixed(2)} ${c2[0].toFixed(2)} ${c2[1].toFixed(2)} ${p2[0]} ${p2[1]}`;
  }
  return closed ? `${d} Z` : d;
}
const M = (k, a, pts, c) => ({ k, a, d: smooth(pts), c: !!c });

